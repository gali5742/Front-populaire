import {test,expect} from "@playwright/test";
import {pathToFileURL} from "node:url";
import {resolve} from "node:path";
test("F1 offline political contact, archive, month transition and save recovery",async({page,context})=>{
 const errors:string[]=[],outside:string[]=[];page.on("pageerror",e=>errors.push(e.message));page.on("request",r=>{if(/^https?:/i.test(r.url()))outside.push(r.url())});
 await context.setOffline(true);
 await page.goto(pathToFileURL(resolve("dist-offline/front-populaire-f1.html")).href);
 await expect(page.getByText("F1 合成规则测试（非1934史实）",{exact:false})).toBeVisible();
 await expect(page.getByLabel("可用党资金")).toHaveText("11,000 F");
 await page.locator(".action").nth(1).getByRole("button",{name:"查看方案 >"}).click();
 await page.getByRole("button",{name:"返回",exact:true}).click();
 await expect(page.getByLabel("可用党资金")).toHaveText("11,000 F");
 await page.locator(".action").nth(1).getByRole("button",{name:"查看方案 >"}).click();
 await page.getByRole("button",{name:"确认提交"}).click();
 await expect(page.getByLabel("可用党资金")).toHaveText("10,000 F");
 await expect(page.getByLabel("剩余行动")).toHaveText("仍有 1 次行动可用");
 await page.getByRole("button",{name:"结束本月 →"}).click();
 await page.getByRole("button",{name:"确认提交"}).click();
 await expect(page.getByLabel("可用党资金")).toHaveText("11,000 F");
 await expect(page.getByLabel("剩余行动")).toHaveText("仍有 2 次行动可用");
 await page.getByRole("button",{name:"档案",exact:true}).click();
 await page.getByLabel("搜索记录").fill("拒绝方案");
 await expect(page.getByText("共 1 条可知记录")).toBeVisible();
 await page.locator(".main-panel").getByRole("button",{name:"查看详情 >"}).click();
 await expect(page.getByRole("dialog")).toContainText("已发生的接触费用不退还");
 await page.getByRole("button",{name:"关闭",exact:true}).click();
 await expect(page.getByLabel("搜索记录")).toHaveValue("拒绝方案");
 await page.getByRole("button",{name:"设置",exact:true}).click();
 const download=page.waitForEvent("download");await page.getByRole("button",{name:"导出存档"}).click();const saved=await (await download).path();if(!saved)throw Error("download unavailable");
 await page.reload();await expect(page.getByText("1934年1月",{exact:true})).toBeVisible();
 await page.getByRole("button",{name:"设置",exact:true}).click();await page.locator("input[type=file]").setInputFiles(saved);
 await expect(page.getByText("1934年2月",{exact:true})).toBeVisible();await expect(page.getByLabel("可用党资金")).toHaveText("11,000 F");
 await page.getByRole("button",{name:"设置",exact:true}).click();await page.locator("input[type=file]").setInputFiles({name:"bad.json",mimeType:"application/json",buffer:Buffer.from("{bad")});
 await expect(page.getByRole("status",{name:"存档反馈"})).toContainText("保留当前会话");await page.getByRole("button",{name:"关闭",exact:true}).click();
 await expect(page.getByText("1934年2月",{exact:true})).toBeVisible();expect(outside).toEqual([]);expect(errors).toEqual([]);
});
